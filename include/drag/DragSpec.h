#pragma once

// 控件拖拽原语的数据（**纯数据，无逻辑**）。
//
// 这一层只回答两个问题：「我能不能被拖」「我收不收」——**不回答**"怎么起拖、
// 幽灵长什么样、什么时候落"。那三件事在场景侧（`drag/InkingDragSession.h`），
// 因为只有场景知道指针、命中与层序。
//
// ---------------------------------------------------------------------------
// 为什么是"数据 + 回调"而不是继承
// ---------------------------------------------------------------------------
// 本库的既有风格是声明式的（`ButtonData` / `PanelData` / `GoldingRegionItemDecl`），
// 不是派生类。拖拽照这条走：给 `InkingWidget` 两组 setter + 两个纯数据结构，
// 于是**任何**控件都能被拖、当落点，连"是不是按钮"都不用问。
//
// ---------------------------------------------------------------------------
// 三条边界（写在这里，免得调用方猜）
// ---------------------------------------------------------------------------
//   1. **payload 归调用方**。库原样转交 `void*`：不解引用、不 clone、不释放。
//      源控件在拖拽期间被删掉时库**只清指针、不访问**（见任务书 §6 风险表）；
//   2. **类型标签是 `const char*`，按内容比较**（`strcmp`）。写成字符串字面量
//      最省心；动态拼出来的串**必须**活得比这组 spec 长；
//   3. **幽灵只是"跟着指针走的一块板"**：文案可选，外观不可配。库不认识
//      "选中态 / 高亮边框"长什么样，那是消费方在 `onRender` 里问 `IsDragOver()`
//      自己画的（和 `MouseHover()` 同一条分工）。
//
// 明确不做（任务书 §4，理由在那儿）：列表边缘自动滚动、跨窗口 / 跨进程拖拽、
// 多选批量拖、排序 / 落位动画、payload 生命周期管理。

/**
 * 拖拽源：**库不认识 payload 的内容**，只把它原样转交，且不负责释放。
 *
 * 用法（GoldingCore 资源库那种）：给列表行 `SetDragSource({...})`，
 * 把资源 id 塞进 `payload`，`payloadType` 写 `"golding.resource"`；
 * 目录行 `SetDropTarget({...})`，`acceptType` 写同一个串。
 */
struct InkingDragSourceSpec
{
    /// 类型标签（如 `"golding.resource"`）。**空 = 这个控件不可拖**。
    ///
    /// 它同时是"能不能拖"的开关与"谁能接"的判据：落点的 `acceptType` 必须与它
    /// 逐字节相等才高亮 / 可落。
    const char* payloadType = nullptr;

    /// 原样回传给落点；**生命周期归调用方**。
    void* payload = nullptr;

    /// 幽灵上显示的文字（可空）。空 = 幽灵只是一块半透明板。
    const char* ghostText = nullptr;

    /// 幽灵尺寸（设计坐标）；`<= 0` 表示用源控件当前的尺寸。
    ///
    /// 单独给尺寸的场景是"源控件很窄、幽灵要能看清"（列表行 200 宽、
    /// 幽灵要 240）——需求里真出现过，所以留这两个字段而不是写死。
    int ghostWidth = 0;
    int ghostHeight = 0;

    /**
     * 可空：某些位置不能起拖。
     *
     * `(x, y)` 是**按下点**（设计坐标）。返回 0 = 这次按下不当拖拽候选——
     * 典型用法是"行内有拖拽手柄，只有按住手柄才能拖整行"。
     *
     * 它在**按下那一刻**判一次，之后不再问：拖到一半改判会让手势忽有忽无。
     */
    bool (*canBegin)(void* user, float x, float y) = nullptr;

    /// `canBegin` 的用户数据；库只转交。
    void* user = nullptr;
};

/**
 * 落点：只有 `acceptType` 与源的 `payloadType` 相等时才高亮 / 可落。
 *
 * 落点按**最近祖先**解析：指针下命中的是行里的标签，而标签没声明落点，
 * 就沿父链往上找——第一个类型匹配的祖先算落点。类型不匹配的祖先**会被跳过**
 * （继续往上找），所以"行不接受这种类型、外层列表接受"是有效配置。
 */
struct InkingDropTargetSpec
{
    /// 接受的类型标签。**空 = 这个控件不是落点**。
    const char* acceptType = nullptr;

    /**
     * 可空：现在能不能落。返回 0 = 不可落（不高亮、松手也不调 `onDrop`）。
     *
     * `(x, y)` 是当前指针位置（设计坐标）。每帧指针动一次问一次，所以它要便宜、
     * 且**不许有副作用**（不许在里面改树 / 改清单）。
     */
    int (*canDrop)(void* user, void* payload, float x, float y) = nullptr;

    /**
     * 落下时调**一次**。参数里 `(x, y)` 是松手那一刻的指针位置（设计坐标）。
     *
     * 调用时机在**会话收尾之后**（幽灵已经删掉、高亮已经清）：回调里删节点、
     * 删 payload、重建整个列表都安全。反过来说——回调里**读不到**"正在拖的那个
     * 源"（`GetDragSourceNode()` 已经是 `nullptr`），要源控件的信息请在
     * `payload` 里带上自己需要的那一份。
     */
    void (*onDrop)(void* user, void* payload, float x, float y) = nullptr;

    /// `canDrop` / `onDrop` 的用户数据；库只转交。
    void* user = nullptr;
};

/// 幽灵层的 z：高于弹窗（400）与菜单（260），低于光标层（900）。
///
/// 光标必须永远在最上（它要指哪画哪），弹窗必须在幽灵之下（拖拽期间不该
/// 弹窗盖住"我要放到哪儿"）。这两条都由这一个常量钉住，业务不必自己调。
inline constexpr int InkingDragGhostZIndex = 850;

/// 起拖阈值（设计像素）：按下后指针移动**超过**这个距离才算开始拖。
///
/// 没有阈值的话按钮永远点不下去——人按下时手一定会抖一两个像素
/// （任务书 §6 风险表第一条，A1 断言钉的就是它）。
inline constexpr float InkingDragStartThreshold = 4.0f;
